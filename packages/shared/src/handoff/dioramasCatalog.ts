import type { CityId, CityRegionProfile, DioramaSpec, ZoneEncounter } from './types';

function makeZone(
  zoneId: ZoneEncounter['zoneId'],
  name: string,
  paduanoPacingType: ZoneEncounter['paduanoPacingType'],
  tacticalRole: string,
  boundingBox: ZoneEncounter['boundingBox'],
  carvedSlices: ZoneEncounter['carvedSlices'],
  garrison: ZoneEncounter['garrison'],
  opts?: {
    elevationModifiers?: ZoneEncounter['elevationModifiers'];
    subProps?: ZoneEncounter['subProps'];
    bloodGate?: ZoneEncounter['bloodGate'];
    baseElevation?: ZoneEncounter['baseElevation'];
  },
): ZoneEncounter {
  return {
    zoneId,
    name,
    paduanoPacingType,
    tacticalRole,
    boundingBox,
    baseElevation: opts?.baseElevation ?? 0,
    carvedSlices,
    elevationModifiers: opts?.elevationModifiers ?? [],
    subProps: opts?.subProps ?? [],
    bloodGate: opts?.bloodGate,
    garrison,
  };
}

